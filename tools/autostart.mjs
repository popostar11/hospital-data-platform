/**
 * 开机自启管理（适用于大屏终端 / 工控机断电重启后自动恢复）
 *
 * 用法：
 *   node tools/autostart.mjs install     安装（写入当前用户「启动」文件夹）
 *   node tools/autostart.mjs uninstall   卸载
 *   node tools/autostart.mjs status      查看状态
 *
 * 实现说明：
 *   在 %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup 下写一个 .cmd，
 *   Windows 登录后会自动执行它 —— 不需要管理员权限，也不用装成系统服务。
 *   生成的 .cmd 内容保持纯 ASCII：cmd.exe 按当前代码页解析批处理，
 *   路径里若含中文会因编码不一致而找不到文件。
 */
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { pauseIfInteractive } from './lib/tty.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SHORTCUT_NAME = 'HospitalDataPlatform.cmd'

function startupDir() {
  const appData = process.env.APPDATA
  if (!appData) return null
  return join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup')
}

function shortcutPath() {
  const dir = startupDir()
  return dir ? join(dir, SHORTCUT_NAME) : null
}

const action = (process.argv[2] ?? 'status').toLowerCase()
const target = shortcutPath()

if (process.platform !== 'win32') {
  console.error('开机自启管理目前仅支持 Windows。')
  process.exit(1)
}

if (!target) {
  console.error('未找到 APPDATA 环境变量，无法定位「启动」文件夹。')
  process.exit(1)
}

if (action === 'install') {
  // 路径含非 ASCII 字符时给出明确警告，而不是留一个静默失效的自启项
  if (/[^\x20-\x7E]/.test(ROOT)) {
    console.error(`[错误] 项目路径包含非 ASCII 字符：${ROOT}`)
    console.error('       cmd 解析批处理时按当前代码页解码，中文路径会导致自启失败。')
    console.error('       请把项目移动到纯英文路径（例如 D:\\hospital-platform）后重试。')
    process.exit(1)
  }
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(
    target,
    [
      '@echo off',
      'rem Auto-generated by tools/autostart.mjs -- do not edit by hand.',
      'rem Keep this file ASCII-only (see docs/DEPLOY.md).',
      `cd /d "${ROOT}"`,
      'node "tools\\launch.mjs"',
      '',
    ].join('\r\n'),
    'utf8',
  )
  console.log()
  console.log('  已设置开机自启。')
  console.log(`  启动项文件：${target}`)
  console.log('  下次登录 Windows 时将自动启动服务（约 10 秒后可用）。')
  console.log()
  console.log('  注意：如需大屏终端开机自动全屏显示，请再把浏览器设为 Kiosk 模式自启，')
  console.log('        见 docs/DEPLOY.md「大屏终端配置」一节。')
  console.log()
} else if (action === 'uninstall') {
  if (existsSync(target)) {
    rmSync(target, { force: true })
    console.log(`  已取消开机自启（已删除 ${target}）。`)
  } else {
    console.log('  当前未设置开机自启，无需取消。')
  }
} else {
  console.log()
  console.log(`  开机自启：${existsSync(target) ? '已设置' : '未设置'}`)
  console.log(`  启动项文件：${target}`)
  console.log(`  项目路径：${ROOT}`)
  console.log()
}

pauseIfInteractive()
