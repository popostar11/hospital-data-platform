/**
 * 后台服务管理：安装 / 卸载 / 状态 / 启动 / 停止
 *
 * 安装后效果：
 *   - 登录 Windows 时自动以**隐藏方式**启动守护进程（无窗口，不会被误关）
 *   - 服务异常退出会在 3 秒内自动重启
 *   - 控制台里按 Ctrl+C 不会影响它（守护进程忽略 SIGINT）
 *   → 也就是「随时打开都能用」
 *
 * 实现方式：在「启动」文件夹放一个 .vbs，用 WScript.Shell 以隐藏窗口方式
 * 拉起 node tools/serve-daemon.mjs。不需要管理员权限，也不用装成系统服务。
 *
 * 用法：
 *   node tools/autostart.mjs install     安装并立即启动
 *   node tools/autostart.mjs uninstall   停止并移除自启
 *   node tools/autostart.mjs status      查看状态
 *   node tools/autostart.mjs start|stop  只启停，不改自启
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { pauseIfInteractive } from './lib/tty.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const VBS_NAME = 'HospitalPlatformDaemon.vbs'
const PID_FILE = join(ROOT, 'data', 'daemon.pid')
const PORT = Number(process.env.PORT ?? 3000)

function startupDir() {
  const appData = process.env.APPDATA
  return appData ? join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup') : null
}
const vbsPath = () => {
  const dir = startupDir()
  return dir ? join(dir, VBS_NAME) : null
}

/* ---------------------------------------------------------------- 工具 */
const nodeExe = process.execPath
const daemonScript = join(ROOT, 'tools', 'serve-daemon.mjs')

/** 记录在案的守护进程 PID（并校验该进程确实还在） */
function daemonPid() {
  if (!existsSync(PID_FILE)) return null
  const pid = Number(readFileSync(PID_FILE, 'utf8').trim())
  if (!Number.isFinite(pid) || pid <= 0) return null
  const r = spawnSync('tasklist', ['/FI', `PID eq ${pid}`, '/NH'], { encoding: 'utf8', windowsHide: true })
  return /node\.exe/i.test(r.stdout ?? '') ? pid : null
}

function serverPid() {
  const r = spawnSync('netstat', ['-ano', '-p', 'TCP'], { encoding: 'utf8', windowsHide: true })
  for (const line of (r.stdout ?? '').split(/\r?\n/)) {
    const m = line.match(/^\s*TCP\s+\S+:(\d+)\s+\S+\s+LISTENING\s+(\d+)\s*$/i)
    if (m && Number(m[1]) === PORT) return Number(m[2])
  }
  return null
}

function killPid(pid, label) {
  if (!pid) return false
  const r = spawnSync('taskkill', ['/pid', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true })
  const ok = r.status === 0
  console.log(ok ? `  已停止 ${label}（PID ${pid}）` : `  停止 ${label}（PID ${pid}）失败，可能需要管理员权限`)
  return ok
}

/** 写隐藏启动项：.vbs 内容保持纯 ASCII，避免 WSH 的编码问题 */
function writeStartupEntry() {
  const path = vbsPath()
  if (!path) {
    console.error('  [错误] 未找到 APPDATA，无法定位「启动」文件夹')
    return false
  }
  if (/[^\x20-\x7E]/.test(ROOT)) {
    console.error(`  [错误] 项目路径含非 ASCII 字符：${ROOT}`)
    console.error('         请把项目移到纯英文路径（例如 D:\\hospital-platform）后重试')
    return false
  }
  mkdirSync(dirname(path), { recursive: true })
  const vbs = [
    "' Hospital Data Platform - hidden daemon launcher (generated by tools/autostart.mjs)",
    "' Keep this file ASCII-only: WSH may mis-parse non-ASCII content.",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${ROOT}"`,
    `sh.Run """${nodeExe}"" ""${daemonScript}""", 0, False`,
    '',
  ].join('\r\n')
  writeFileSync(path, vbs, 'utf8')
  console.log(`  已写入启动项：${path}`)
  return true
}

function startDaemonNow() {
  if (daemonPid()) {
    console.log('  守护进程已在运行')
    return
  }
  // 以隐藏窗口方式立即拉起（与登录时的方式完全一致）
  spawnSync('wscript.exe', [vbsPath()], { stdio: 'ignore', windowsHide: true })
  console.log('  已通过隐藏方式启动守护进程')
}

/* ---------------------------------------------------------------- 动作 */
const action = (process.argv[2] ?? 'status').toLowerCase()

if (process.platform !== 'win32') {
  console.error('后台服务管理目前仅支持 Windows。')
  process.exit(1)
}

console.log()
if (action === 'install') {
  console.log('【安装后台服务】')
  if (!writeStartupEntry()) process.exit(1)
  startDaemonNow()
  console.log()
  console.log('  完成。登录 Windows 后自动启动，服务异常退出会 3 秒内自动重启。')
  console.log(`  现在即可访问：http://127.0.0.1:${PORT}/`)
  console.log()
  console.log('  日志：logs/server.log（服务）｜ logs/daemon.log（守护进程）')
  console.log('  停止：双击「停止.bat」；取消自启：双击「取消开机自启.bat」')
} else if (action === 'uninstall') {
  console.log('【卸载后台服务】')
  killPid(daemonPid(), '守护进程')
  killPid(serverPid(), '服务进程')
  const path = vbsPath()
  if (path && existsSync(path)) {
    rmSync(path, { force: true })
    console.log(`  已删除启动项：${path}`)
  } else {
    console.log('  未发现启动项，无需删除')
  }
  rmSync(PID_FILE, { force: true })
} else if (action === 'start') {
  console.log('【启动服务】')
  startDaemonNow()
} else if (action === 'stop') {
  console.log('【停止服务】')
  killPid(daemonPid(), '守护进程')
  killPid(serverPid(), '服务进程')
  rmSync(PID_FILE, { force: true })
} else {
  const vbs = vbsPath()
  const d = daemonPid()
  const s = serverPid()
  console.log('【后台服务状态】')
  console.log(`  自启项：${vbs && existsSync(vbs) ? '已安装' : '未安装'}`)
  console.log(`  守护进程：${d ? `运行中（PID ${d}）` : '未运行'}`)
  console.log(`  服务进程：${s ? `运行中（PID ${s}，端口 ${PORT}）` : '未运行'}`)
  console.log(`  访问地址：http://127.0.0.1:${PORT}/`)
  console.log(`  项目路径：${ROOT}`)
}
console.log()
pauseIfInteractive()
